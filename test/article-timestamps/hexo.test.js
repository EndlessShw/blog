'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const Hexo = require('hexo');
const { fixture } = require('./fixtures');

test('真实 Hexo/Fluid 页面：首次相同隐藏、附件更新显示、缓存复用、发布时间及排序不变', async t => {
  const f = fixture(t);
  f.write('package.json', JSON.stringify({ name: 'timestamp-fixture', version: '1.0.0', hexo: { version: '8.1.2' } }));
  f.write('.gitignore', 'public/\ndb.json\nnode_modules/\nthemes/\n');
  f.write('_config.yml', `title: Timestamp test\nurl: https://example.invalid\npermalink: :title/\ntimezone: Asia/Shanghai\nlanguage: zh-CN\nsource_dir: source\npublic_dir: public\ntheme: fluid\nupdated_option: date\npost_asset_folder: true\nindex_generator:\n  per_page: 10\n  order_by: -date\n`);
  f.write('_config.fluid.yml', 'post:\n  updated:\n    enable: true\n    relative: false\n    date_format: "YYYY-MM-DD HH:mm:ss"\n');
  const script = fs.readFileSync(path.resolve('scripts/article-timestamps.js'), 'utf8').replace("'../lib/article-timestamps'", JSON.stringify(path.resolve('lib/article-timestamps')));
  f.write('scripts/article-timestamps.js', script);
  f.write('source/_posts/older.md', '---\ntitle: Old post\ndate: 2020-01-01 12:00:00\nupdated: 2099-01-01\n---\n![图片](/img/shared.png)\n');
  f.write('source/img/shared.png', Buffer.from([0, 1])); f.commit(1);
  f.write('source/_posts/newer.md', '---\ntitle: New post\ndate: 2020-01-02 12:00:00\n---\n# New post\n'); f.commit(2);
  f.write('themes/.keep', '');
  const themeLink = path.join(f.root, 'themes/fluid');
  fs.symlinkSync(path.dirname(require.resolve('hexo-theme-fluid/package.json')), themeLink, 'junction');
  f.beforeCleanup(() => fs.unlinkSync(themeLink));
  const modulesLink = path.join(f.root, 'node_modules');
  fs.symlinkSync(path.resolve('node_modules'), modulesLink, 'junction');
  f.beforeCleanup(() => fs.unlinkSync(modulesLink));
  const hexo = new Hexo(f.root, { silent: true });
  f.beforeCleanup(() => hexo.exit());
  await hexo.init();
  for (const name of ['hexo-renderer-marked', 'hexo-renderer-ejs', 'hexo-renderer-stylus', 'hexo-generator-index', 'hexo-generator-archive']) await hexo.loadPlugin(require.resolve(name));
  await hexo.call('generate', { force: true });
  const read = file => fs.readFileSync(path.join(f.root, 'public', file), 'utf8');
  assert.equal(read('older/index.html').includes('id="updated-time"'), false, '相同日期应隐藏更新时间');
  const beforePost = fs.readFileSync(path.join(f.root, 'source/_posts/older.md'));
  const publication = hexo.model('Post').findOne({ slug: 'older' }).date.valueOf();
  f.write('source/img/shared.png', Buffer.from([0, 2])); const image = f.commit(3);
  await hexo.call('generate', { force: true });
  const oldHtml = read('older/index.html');
  assert.match(oldHtml, /id="updated-time"[\s\S]*?2020-01-03 12:00:00/);
  assert.ok(oldHtml.includes('property="article:modified_time" content="2020-01-03T04:00:00.000Z"'));
  assert.ok(oldHtml.includes('property="article:published_time" content="2020-01-01T04:00:00.000Z"'));
  assert.equal(hexo.model('Post').findOne({ slug: 'older' }).date.valueOf(), publication);
  assert.deepEqual(fs.readFileSync(path.join(f.root, 'source/_posts/older.md')), beforePost);
  assert.match(oldHtml, /2020-01-01/);
  const index = read('index.html');
  assert.ok(index.indexOf('href="/newer/"') < index.indexOf('href="/older/"'));
  const archive = read('archives/index.html');
  assert.ok(archive.indexOf('href="/newer/"') < archive.indexOf('href="/older/"'));
  assert.doesNotMatch(read('newer/index.html'), /id="updated-time"/);
  const cli = path.resolve('tools/article-timestamps.js');
  const snapshot = zone => JSON.parse(execFileSync(process.execPath, [cli, '--root', f.root], { encoding: 'utf8', env: { ...process.env, TZ: zone } }));
  const utc = snapshot('UTC');
  const older = utc.articles.find(a => /older\.md$/.test(a.file));
  assert.equal(older.source.sha, image); assert.equal(older.updated, '2020-01-03T12:00:00+08:00');
  // Same committed content, different checkout line endings and filesystem times.
  f.write('source/_posts/older.md', beforePost.toString().replace(/\n/g, '\r\n'));
  fs.utimesSync(path.join(f.root, 'source/_posts/older.md'), new Date('2035-01-01Z'), new Date('2035-01-01Z'));
  assert.deepEqual(snapshot('America/Los_Angeles').articles, utc.articles);
});
